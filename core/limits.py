# core/limits.py
"""Единый источник лимитов и порогов.

Вынесено отдельным модулем БЕЗ импортов из проекта, чтобы его могли
импортировать и ядро (core/texts.py), и адаптеры (adapters/*) без
риска циклических импортов.

ВАЖНО: значения должны совпадать с историческими (MAX_PHOTOS=10,
MAX_BANNER_SIZE=15 МБ, MAX_DOC_SIZE=10 МБ, MAX_TEXT_LENGTH=2000) —
менять их без отдельного решения нельзя.
"""

# --- Лимиты вложений и текста ---
MAX_PHOTOS = 10
MAX_BANNER_SIZE = 15 * 1024 * 1024
MAX_DOC_SIZE = 10 * 1024 * 1024
MAX_TEXT_LENGTH = 2000

# Максимум вложений в одном сообщении, которые вообще уходят на релей в VK.
MAX_ATTACHMENTS = 12

# --- Лимиты входящего payload ---
# Telegram ограничивает callback_data 64 байтами, VK — заметно больше,
# поэтому произвольный payload может быть длинным.
MAX_PAYLOAD_LEN = 4096

# --- Лимиты частоты ---
# Лимит на ЛЮБЫЕ события (текст, кнопки, вложения) в минуту.
# check_message_rate() считает только текстовые сообщения, поэтому
# события с payload нуждаются в отдельном счётчике.
EVENT_RATE_LIMIT = 60

# Разрешённые расширения документов.
ALLOWED_DOC_EXT = {
    "pdf", "jpg", "jpeg", "png", "gif", "bmp", "webp", "tiff", "doc", "docx",
}

# Хосты, с которых разрешено скачивать медиа (защита от SSRF).
ALLOWED_MEDIA_HOSTS = (
    "userapi.com", "vkuserphoto.ru", "vk.com", "vk.ru", "cdn.telegram.org",
    # MAX CDN:
    #   i.oneme.ru  — иконки/аватарки MAX (уже было)
    #   fd.oneme.ru — файловый CDN: PDF квитанции, документы, фото,
    #                 которые MAX принимает у пользователя
    # Достаточно `oneme.ru` — endswith(".oneme.ru") покрывает оба
    # поддомена и не откроет произвольные сторонние хосты.
    "fd.oneme.ru",
    "oneme.ru",
)

# Сколько URL из текста сообщения бот релеит как вложения.
# Одинаково для VK и TG — иначе поведение зависит от платформы админа.
MAX_RELAY_URLS_PER_MSG = 5